const assert = require("node:assert/strict");
const fs = require("node:fs");

const html = fs.readFileSync("index.html", "utf8");
const css = fs.readFileSync("js/medley-editor.css", "utf8");
const topbarCss = fs.readFileSync("css/topbar-labels.css", "utf8");
const source = html.slice(html.indexOf("let medleyBlocos=[];"), html.indexOf("function tocarMedley(){"));

assert.match(html, /medley-editor\.css\?v=30/);
assert.ok(html.indexOf('css/roudy-color-system-preview.css?v=15') < html.indexOf('js/medley-editor.css?v=30'), 'o CSS específico do Medley deve prevalecer sobre a camada global de cores');
assert.match(css, /\.medley-editor-header\{margin:-22px 0 12px\}/, 'o título do Medley deve alinhar verticalmente com o título de Eventos');
assert.match(css, /\.medley-editor-subline\{display:flex;margin-top:22px;/, 'os metadados e o botão de tom devem ter respiro abaixo do título');
assert.match(css, />\.topbar\{border-bottom:0;background:transparent;box-shadow:none\}/);
assert.match(source, /Várias músicas, uma boa ideia\./);
assert.match(source, /Escolha uma parte da sua playlist para começar o medley\./);
assert.match(html, /Todo show começa com uma data\./);
assert.match(html, /Crie seu primeiro evento e comece a organizar a banda\./);
assert.match(source, /assets\/empty-medley-disc\.svg/);
assert.match(html, /assets\/empty-events-calendar\.svg/);
assert.match(source, /<h1 class="medley-editor-title">Medley<\/h1>/);
assert.doesNotMatch(source, /medley-editor-kicker/, "o rótulo redundante foi removido");
assert.match(source, /medley-compact-header/);
assert.match(source, /Sustenidos \(#\)/, 'o seletor de tom deve oferecer sustenidos');
assert.match(source, /Bemóis \(♭\)/, 'o seletor de tom deve oferecer bemóis');
assert.match(source, /requestAnimationFrame\(updateMedleyScrollState\)/, "scroll é consolidado por frame");
assert.match(source, /titleRect\.bottom<=8/, "compacto só surge depois que o título principal sai");
assert.match(source, /medleyMeta\(\)/);
assert.match(source, /renderMedleySheetMusic/);
assert.match(source, /Buscar música na sua biblioteca/);
assert.match(source, /medleySheetBlockIndex==null/);
assert.match(source, /String\(block\.c\|\|''\)\.trim\(\)/, "partes vazias são excluídas");
assert.match(source, /if\(medleyAdding\)return/, "duplo clique é bloqueado");
assert.match(source, /saveCurrentMedley\(\)/, "alterações persistem no rascunho");
assert.match(source, /ondragstart="startMedleyDrag/);
assert.match(source, /class="medley-drag"[\s\S]*?<path d="M5 8h14M5 12h14M5 16h14"/, "o Medley usa o mesmo ícone de três traços do ordenador de repertório");
assert.doesNotMatch(css, /\.medley-drag::before/, "o antigo ícone de seis pontos foi removido");
assert.match(source, /medley-key-chip/);
assert.match(source, /Editar trecho/);
assert.match(source, /Ajustar tom/);
assert.match(source, /Excluir bloco/);
assert.match(source, /function setMedleyGlobalKey/);
assert.match(source, /function setMedleyBlockKey/);
assert.match(source, /block\.label=label;block\.chords=chords/, 'a edição altera somente a cópia do bloco no Medley');
assert.match(source, /Math\.abs\(gesture\.rotation\)>=170/, "giro usa limiar antes de salvar");
assert.match(source, /Math\.abs\(gesture\.rotation\)\/170\*100/, "contorno acompanha o progresso angular");
assert.match(source, /medley-vinyl-progress/);
assert.match(source, /const moved=Math\.abs\(gesture\.rotation\)>=8/, "giro interrompido não vira toque acidental");
assert.match(source, /abrirSalvarMedley\(\)/, "toque e gesto convergem no mesmo fluxo");
assert.match(source, /if\(medleySaveState==='saving'\)return/, "salvamento duplicado é bloqueado");
assert.ok(source.indexOf("if(!saved)") < source.indexOf("medleyBlocos=[]", source.indexOf("function confirmarSalvarMedley")), "falha retorna antes de limpar o rascunho");
assert.match(css, /prefers-reduced-motion:reduce/);
assert.match(css, /touch-action:none/);
assert.match(css, /radial-gradient\(ellipse 88% 330px at 0 0/, "a luz branca nasce no canto superior esquerdo extremo");
assert.match(css, /rgba\(255,255,255,var\(--medley-light-strong\)\)/, "a luz usa opacidade compatível com o navegador");
assert.match(css, /#view-main\[data-active-tab="medley"\]::before\{display:none\}/, "não existe camada intermediária que forme uma faixa");
assert.match(css, /topbar:has\(\.topbar-search-mode:not\(\[hidden\]\)\)\{background:#0b0b0c/, "o cabeçalho da busca usa o mesmo grafite claro dos resultados");
assert.match(css, /playlist-search-recents\{background:#0b0b0c\}/, "a busca do Medley usa uma única superfície contínua");
assert.match(topbarCss, /data-active-tab="medley"[^}]*\.app-assistant-launch[^}]*\.topbar-camera-action\{display:none!important\}/, "no Medley ficam somente busca, notificações e menu");
assert.match(topbarCss, /#view-main \.topbar-labeled::after\{display:none\}/, "os ícones superiores não exibem legendas visuais");
assert.match(css, /stroke:#0789e7/, "o progresso usa o azul ROUDY");
assert.match(css, /stroke-dashoffset:calc\(100 - var\(--vinyl-progress\)\)/);
assert.match(css, /\.medley-vinyl/);
assert.doesNotMatch(css, /neon/i);

console.log("medley-editor-ui.test.js: OK");
